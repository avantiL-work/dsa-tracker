//to print numbers from 1 to 100 using while loop
public class Whileloop1to100{
    public static void main(String args[]){
//because we want to print numbers from 1 to 100 we begin the counter from 1
        int counter = 1;

        while(counter <= 100){
            System.out.println(counter);
            counter++;
        }

        System.out.println("printed numbers from 1 to 100");
    }
}